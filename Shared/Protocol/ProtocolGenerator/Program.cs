using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

if (args.Length != 2)
{
    Console.Error.WriteLine("Usage: ProtocolGenerator <game_messages.proto> <output-directory>");
    return 2;
}

var protoPath = Path.GetFullPath(args[0]);
var outputDirectory = Path.GetFullPath(args[1]);

if (!File.Exists(protoPath))
{
    Console.Error.WriteLine($"Protocol file not found: {protoPath}");
    return 2;
}

try
{
    var schema = ProtoSchema.Parse(File.ReadAllLines(protoPath));
    Directory.CreateDirectory(outputDirectory);
    WriteProtocols(schema, Path.Combine(outputDirectory, "Protocols.cs"));
    WriteMessages(schema, Path.Combine(outputDirectory, "GameMessages.cs"));
    WriteGameThreeBallCatalog(
        Path.Combine(Path.GetDirectoryName(protoPath)!, "game_three_balls.json"),
        Path.Combine(outputDirectory, "GameThreeBallCatalogData.cs"));
    WriteGameThreeMatchBalance(
        Path.Combine(Path.GetDirectoryName(protoPath)!, "game_three_match_balance.json"),
        Path.Combine(outputDirectory, "GameThreeMatchBalanceData.cs"));
    WriteGameThreePowerUpCatalog(
        Path.Combine(Path.GetDirectoryName(protoPath)!, "game_three_powerups.json"),
        Path.Combine(outputDirectory, "GameThreePowerUpCatalogData.cs"));
    WriteGameThreeAbilityCatalog(
        Path.Combine(Path.GetDirectoryName(protoPath)!, "game_three_abilities.json"),
        Path.Combine(outputDirectory, "GameThreeAbilityCatalogData.cs"));
    Console.WriteLine($"Generated protocol C# files from {protoPath}");
    return 0;
}
catch (Exception exception)
{
    Console.Error.WriteLine($"Protocol generation failed: {exception.Message}");
    return 1;
}

