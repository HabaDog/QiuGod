static void ValidateCatalogItem(GameThreeBallCatalogItem item)
{
    if (string.IsNullOrWhiteSpace(item.BallId) || string.IsNullOrWhiteSpace(item.DisplayName)
        || string.IsNullOrWhiteSpace(item.SkillId) || string.IsNullOrWhiteSpace(item.SkillKind)
        || string.IsNullOrWhiteSpace(item.SkillDisplayName) || string.IsNullOrWhiteSpace(item.SkillDescription)
        || item.MaxHealth <= 0 || item.MoveSpeed <= 0f || item.JumpForce <= 0f
        || item.Mass <= 0f || item.EnergyRequired <= 0 || item.SkillDuration < 0f || item.SkillSelfDamagePerSecond < 0f
        || item.SkillEffectRed is < 0f or > 1f || item.SkillEffectGreen is < 0f or > 1f || item.SkillEffectBlue is < 0f or > 1f
        || item.SkillBurstSeconds <= 0f || item.SkillAnnouncementSeconds <= 0f
        || string.IsNullOrWhiteSpace(item.PrimaryAttackAbilityId))
    {
        throw new InvalidOperationException($"Invalid GameThree ball catalog entry: {item.BallId}");
    }
}

