static void WriteProtocols(ProtoSchema schema, string outputPath)
{
    var builder = new StringBuilder();
    builder.AppendLine("// <auto-generated />");
    builder.AppendLine("// Source: Shared/Protocol/game_messages.proto");
    builder.AppendLine();
    builder.AppendLine("namespace GameNetworkCommon");
    builder.AppendLine("{");
    builder.AppendLine("    public static class Protocols");
    builder.AppendLine("    {");

    foreach (var item in schema.Protocols.Where(item => item.Name != "ProtocolIdUnknown"))
    {
        builder.AppendLine($"        public const ushort {item.Name} = {item.Value};");
    }

    builder.AppendLine("    }");
    builder.AppendLine("}");
    WriteIfChanged(outputPath, builder.ToString());
}

static void WriteMessages(ProtoSchema schema, string outputPath)
{
    var builder = new StringBuilder();
    builder.AppendLine("// <auto-generated />");
    builder.AppendLine("// Source: Shared/Protocol/game_messages.proto");
    builder.AppendLine();
    builder.AppendLine("using System.Collections.Generic;");
    builder.AppendLine("using ProtoBuf;");
    builder.AppendLine();
    builder.AppendLine("namespace GameNetworkCommon");
    builder.AppendLine("{");

    foreach (var message in schema.Messages)
    {
        builder.AppendLine("    [ProtoContract]");
        builder.AppendLine($"    public class {message.Name}");
        builder.AppendLine("    {");

        foreach (var field in message.Fields)
        {
            builder.AppendLine($"        [ProtoMember({field.Number})]");
            builder.AppendLine($"        public {GetCSharpType(field)} {field.Name} {{ get; set; }}{GetInitializer(field)}");
            builder.AppendLine();
        }

        if (message.Fields.Count > 0)
        {
            builder.Length -= Environment.NewLine.Length;
        }

        builder.AppendLine("    }");
        builder.AppendLine();
    }

    if (schema.Messages.Count > 0)
    {
        builder.Length -= Environment.NewLine.Length;
    }

    builder.AppendLine("}");
    WriteIfChanged(outputPath, builder.ToString());
}

static void WriteIfChanged(string outputPath, string content)
{
    if (File.Exists(outputPath)
        && string.Equals(File.ReadAllText(outputPath), content, StringComparison.Ordinal))
    {
        return;
    }

    var temporaryPath = outputPath + ".tmp";
    File.WriteAllText(temporaryPath, content, new UTF8Encoding(false));
    File.Move(temporaryPath, outputPath, true);
}

static string GetCSharpType(ProtoField field)
{
    var typeName = field.Type switch
    {
        "bool" => "bool",
        "float" => "float",
        "int32" => "int",
        "int64" => "long",
        "string" => "string",
        _ => field.Type
    };

    return field.IsRepeated ? $"List<{typeName}>" : typeName;
}

static string GetInitializer(ProtoField field)
{
    if (!string.IsNullOrWhiteSpace(field.CSharpDefault))
    {
        return $" = {NormalizeDefault(field)};";
    }

    if (field.IsRepeated)
    {
        return $" = new {GetCSharpType(field)}();";
    }

    return field.Type == "string" ? " = string.Empty;" : string.Empty;
}

static string NormalizeDefault(ProtoField field)
{
    if (field.IsRepeated)
    {
        throw new InvalidOperationException($"Repeated field {field.MessageName}.{field.Name} cannot have csharp_default.");
    }

    var value = field.CSharpDefault.Trim();
    return field.Type switch
    {
        "bool" when bool.TryParse(value, out var parsedBool) => parsedBool ? "true" : "false",
        "int32" when int.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsedInt) =>
            parsedInt.ToString(CultureInfo.InvariantCulture),
        "int64" when long.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsedLong) =>
            parsedLong.ToString(CultureInfo.InvariantCulture) + "L",
        "float" when float.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var parsedFloat) =>
            parsedFloat.ToString("R", CultureInfo.InvariantCulture) + "f",
        _ => throw new InvalidOperationException(
            $"Invalid csharp_default '{value}' for {field.MessageName}.{field.Name} ({field.Type}).")
    };
}

sealed record ProtoSchema(IReadOnlyList<ProtocolItem> Protocols, IReadOnlyList<ProtoMessage> Messages)
{
    private const int MaxFieldNumber = 536_870_911;
    private static readonly HashSet<string> ScalarTypes = new(StringComparer.Ordinal)
    {
        "bool", "float", "int32", "int64", "string"
    };
    private static readonly Regex ProtocolRegex = new(
        @"^\s*(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?<value>\d+)\s*;\s*(?://.*)?$",
        RegexOptions.Compiled);
    private static readonly Regex MessageRegex = new(
        @"^\s*message\s+(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*\{\s*$",
        RegexOptions.Compiled);
    private static readonly Regex FieldRegex = new(
        @"^\s*(?<repeated>repeated\s+)?(?<type>[A-Za-z_][A-Za-z0-9_]*)\s+(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?<number>\d+)\s*;\s*(?://\s*csharp_default=(?<default>.+?)\s*)?$",
        RegexOptions.Compiled);

    public static ProtoSchema Parse(IReadOnlyList<string> lines)
    {
        var protocols = new List<ProtocolItem>();
        var messages = new List<ProtoMessage>();
        var protocolNames = new HashSet<string>(StringComparer.Ordinal);
        var protocolValues = new HashSet<ushort>();
        var messageNames = new HashSet<string>(StringComparer.Ordinal);
        var inProtocolEnum = false;
        var sawProtocolEnum = false;
        ProtoMessage? currentMessage = null;

        for (var index = 0; index < lines.Count; index++)
        {
            var lineNumber = index + 1;
            var line = lines[index].TrimEnd();
            var trimmed = line.Trim();

            if (string.IsNullOrEmpty(trimmed) || trimmed.StartsWith("//", StringComparison.Ordinal))
            {
                continue;
            }

            if (inProtocolEnum)
            {
                if (trimmed == "}")
                {
                    inProtocolEnum = false;
                    continue;
                }

                var protocolMatch = ProtocolRegex.Match(line);
                if (!protocolMatch.Success)
                {
                    throw ParseError(lineNumber, "Unsupported ProtocolId declaration", line);
                }

                var protocolName = protocolMatch.Groups["name"].Value;
                if (!uint.TryParse(protocolMatch.Groups["value"].Value, out var rawValue)
                    || rawValue > ushort.MaxValue)
                {
                    throw ParseError(lineNumber, "Protocol ID must fit in ushort", line);
                }

                var protocolValue = (ushort)rawValue;
                if (!protocolNames.Add(protocolName))
                {
                    throw ParseError(lineNumber, $"Duplicate protocol name {protocolName}", line);
                }

                if (!protocolValues.Add(protocolValue))
                {
                    throw ParseError(lineNumber, $"Duplicate protocol ID {protocolValue}", line);
                }

                protocols.Add(new ProtocolItem(protocolName, protocolValue));
                continue;
            }

            if (currentMessage is not null)
            {
                if (trimmed == "}")
                {
                    messages.Add(currentMessage);
                    currentMessage = null;
                    continue;
                }

                var fieldMatch = FieldRegex.Match(line);
                if (!fieldMatch.Success)
                {
                    throw ParseError(lineNumber, $"Unsupported field declaration in {currentMessage.Name}", line);
                }

                var fieldName = fieldMatch.Groups["name"].Value;
                var fieldNumber = int.Parse(fieldMatch.Groups["number"].Value, CultureInfo.InvariantCulture);
                if (fieldNumber is < 1 or > MaxFieldNumber)
                {
                    throw ParseError(lineNumber, $"Field number must be between 1 and {MaxFieldNumber}", line);
                }

                if (currentMessage.Fields.Any(field => field.Number == fieldNumber))
                {
                    throw ParseError(lineNumber, $"Duplicate field number {fieldNumber} in {currentMessage.Name}", line);
                }

                if (currentMessage.Fields.Any(field => field.Name == fieldName))
                {
                    throw ParseError(lineNumber, $"Duplicate field name {fieldName} in {currentMessage.Name}", line);
                }

                currentMessage.Fields.Add(new ProtoField(
                    currentMessage.Name,
                    fieldName,
                    fieldMatch.Groups["type"].Value,
                    fieldNumber,
                    fieldMatch.Groups["repeated"].Success,
                    fieldMatch.Groups["default"].Value));
                continue;
            }

            if (trimmed.StartsWith("enum ProtocolId", StringComparison.Ordinal))
            {
                if (sawProtocolEnum || trimmed != "enum ProtocolId {")
                {
                    throw ParseError(lineNumber, "ProtocolId enum must be declared exactly once", line);
                }

                sawProtocolEnum = true;
                inProtocolEnum = true;
                continue;
            }

            var messageMatch = MessageRegex.Match(line);
            if (messageMatch.Success)
            {
                var messageName = messageMatch.Groups["name"].Value;
                if (!messageNames.Add(messageName))
                {
                    throw ParseError(lineNumber, $"Duplicate message {messageName}", line);
                }

                currentMessage = new ProtoMessage(messageName, new List<ProtoField>());
                continue;
            }

            if (trimmed.StartsWith("syntax =", StringComparison.Ordinal)
                || trimmed.StartsWith("package ", StringComparison.Ordinal)
                || trimmed.StartsWith("option ", StringComparison.Ordinal))
            {
                continue;
            }

            throw ParseError(lineNumber, "Unsupported top-level declaration", line);
        }

        if (inProtocolEnum)
        {
            throw new InvalidOperationException("ProtocolId enum was not closed.");
        }

        if (currentMessage is not null)
        {
            throw new InvalidOperationException($"Message {currentMessage.Name} was not closed.");
        }

        if (!sawProtocolEnum || protocols.Count == 0)
        {
            throw new InvalidOperationException("ProtocolId enum is missing or empty.");
        }

        foreach (var field in messages.SelectMany(message => message.Fields))
        {
            if (!ScalarTypes.Contains(field.Type) && !messageNames.Contains(field.Type))
            {
                throw new InvalidOperationException(
                    $"Unknown field type {field.Type} on {field.MessageName}.{field.Name}.");
            }

        }

        return new ProtoSchema(protocols, messages);
    }

    private static InvalidOperationException ParseError(int lineNumber, string message, string line)
    {
        return new InvalidOperationException($"Line {lineNumber}: {message}: {line.Trim()}");
    }
}

